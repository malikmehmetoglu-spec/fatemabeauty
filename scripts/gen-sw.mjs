// Generates public/sw.js before every build: precaches the patient-app pages so the
// installed app opens instantly and keeps working with a weak or missing connection.
import { readFileSync, writeFileSync } from "node:fs";

const routes = readFileSync(new URL("../src/lib/routes.ts", import.meta.url), "utf8");
const pages = [...routes.matchAll(/(\w+): "([^"]+)"/g)]
  .filter(([, key]) => !/^(W_|T_|TV_|Site)/.test(key)) // patient app only
  .map(([, , path]) => path);

const version = process.env.VERCEL_GIT_COMMIT_SHA?.slice(0, 8) || Date.now().toString(36);
const precache = [...pages, "/manifest.webmanifest", "/images/fatema.jpg", "/brand/fatema-logo.svg",
  "/brand/fatema-logo-light.svg", "/icons/icon-192.png", "/icons/icon-512.png"];

writeFileSync(new URL("../public/sw.js", import.meta.url), `/* Generated by scripts/gen-sw.mjs — do not edit. */
const CACHE = "fatema-${version}";
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => Promise.allSettled(PRECACHE.map((u) => c.add(u)))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Pages: network first (always fresh), cached copy when offline.
  // Staff screens are never served from cache (always the latest build); the admin app needs the network anyway.
  if (req.mode === "navigate" && /^\/(admin|kiosk|tv|screens)(\/|$)/.test(url.pathname)) return;
  if (req.mode === "navigate") {
    e.respondWith(
      fetch(req).then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
        return res;
      }).catch(() => caches.match(req).then((hit) => hit || caches.match("/")))
    );
    return;
  }

  // Build assets, fonts, images: cache first (file names are content-hashed).
  e.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok && (url.pathname.startsWith("/_next/") || /\\.(png|jpg|jpeg|svg|webp|ttf|woff2?|css|js)$/.test(url.pathname))) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
      }
      return res;
    }))
  );
});
`);
console.log(`sw.js: ${precache.length} files, cache fatema-${version}`);
